function construir_planta_vtol(nombre_modelo)
% CONSTRUIR_PLANTA_VTOL Crea una planta base en Simulink para VTOL.
% Estados: [p_I(3); v_I(3); q_BI(4); w_B(3)].
% Entradas: [empuje; epsilon; gamma_izq; gamma_der; alfa_rud_izq; gamma_rud_izq; alfa_rud_der; gamma_rud_der; beta_aileron].

    if nargin < 1
        nombre_modelo = 'planta_vtol';
    end

    if bdIsLoaded(nombre_modelo)
        close_system(nombre_modelo, 0);
    end

    new_system(nombre_modelo);
    open_system(nombre_modelo);

    % Variables base en workspace.
    assignin('base', 'parametros_vtol', crear_parametros_vtol());
    assignin('base', 'x0_inicial', [zeros(6,1); 1; 0; 0; 0; zeros(3,1)]);

    % Configuracion de simulacion.
    set_param(nombre_modelo, ...
        'Solver', 'ode45', ...
        'StopTime', '20', ...
        'SaveFormat', 'StructureWithTime');

    % Bloques principales.
    bloque_u = [nombre_modelo '/u_control'];
    bloque_dyn = [nombre_modelo '/DinamicaVTOL'];
    bloque_int = [nombre_modelo '/IntegradorEstados'];
    bloque_x = [nombre_modelo '/estado_x'];
    bloque_F = [nombre_modelo '/fuerza_body'];
    bloque_M = [nombre_modelo '/momento_body'];
    bloque_scope_x = [nombre_modelo '/Scope_estados'];
    bloque_scope_FM = [nombre_modelo '/Scope_fuerzas_momentos'];
    bloque_mux_FM = [nombre_modelo '/Mux_FM'];
    bloque_to_x = [nombre_modelo '/ToWorkspace_estado_x'];
    bloque_to_F = [nombre_modelo '/ToWorkspace_fuerza_body'];
    bloque_to_M = [nombre_modelo '/ToWorkspace_momento_body'];

    add_block('simulink/Sources/In1', bloque_u, ...
        'PortDimensions', '9', ...
        'Position', [40 98 70 112]);
    add_block('simulink/User-Defined Functions/MATLAB Function', bloque_dyn, ...
        'Position', [220 70 430 220]);
    add_block('simulink/Continuous/Integrator', bloque_int, ...
        'InitialCondition', 'x0_inicial', ...
        'Position', [510 108 540 142]);

    add_block('simulink/Sinks/Out1', bloque_x, 'Position', [660 108 690 122]);
    add_block('simulink/Sinks/Out1', bloque_F, 'Position', [660 168 690 182]);
    add_block('simulink/Sinks/Out1', bloque_M, 'Position', [660 228 690 242]);
    add_block('simulink/Sinks/Scope', bloque_scope_x, ...
        'NumInputPorts', '1', ...
        'Position', [760 90 900 180]);
    add_block('simulink/Signal Routing/Mux', bloque_mux_FM, ...
        'Inputs', '2', ...
        'Position', [730 180 750 260]);
    add_block('simulink/Sinks/Scope', bloque_scope_FM, ...
        'NumInputPorts', '1', ...
        'Position', [780 180 920 290]);
    add_block('simulink/Sinks/To Workspace', bloque_to_x, ...
        'VariableName', 'estado_x_ws', ...
        'SaveFormat', 'Structure With Time', ...
        'Position', [760 320 910 350]);
    add_block('simulink/Sinks/To Workspace', bloque_to_F, ...
        'VariableName', 'fuerza_body_ws', ...
        'SaveFormat', 'Structure With Time', ...
        'Position', [760 360 910 390]);
    add_block('simulink/Sinks/To Workspace', bloque_to_M, ...
        'VariableName', 'momento_body_ws', ...
        'SaveFormat', 'Structure With Time', ...
        'Position', [760 400 910 430]);

    % Codigo interno del bloque MATLAB Function.
    codigo_bloque = [ ...
        "function [xdot,Fb,Mb] = fcn(x,u)" newline ...
        "%#codegen" newline ...
        "% x = [p_I; v_I; q_BI; w_B]" newline ...
        "% u = [empuje; epsilon; gamma_izq; gamma_der; alfa_rud_izq; gamma_rud_izq; alfa_rud_der; gamma_rud_der; beta_aileron]" newline ...
        "persistent parametros" newline ...
        "if isempty(parametros)" newline ...
        "    parametros = crear_parametros_vtol();" newline ...
        "end" newline ...
        "p = x(1:3);" newline ...
        "vI = x(4:6);" newline ...
        "q = x(7:10);" newline ...
        "w = x(11:13);" newline ...
        "q = q / max(norm(q), 1e-9);" newline ...
        "[Fb, Mb] = modelo_fuerzas_momentos_vtol(x, u, parametros);" newline ...
        "R_BI = quat_a_rot(q);" newline ...
        "gI = [0; 0; -parametros.g];" newline ...
        "p_dot = vI;" newline ...
        "v_dot = (R_BI * Fb) / parametros.m + gI;" newline ...
        "omega_q = [0; w];" newline ...
        "q_dot = 0.5 * quat_mult(q, omega_q);" newline ...
        "% Correccion suave para evitar deriva de norma del cuaternion." newline ...
        "k_norm = 2.0;" newline ...
        "q_dot = q_dot + k_norm * (1 - dot(q, q)) * q;" newline ...
        "w_dot = parametros.I \ (Mb - cross(w, parametros.I * w));" newline ...
        "xdot = [p_dot; v_dot; q_dot; w_dot];" newline ...
        "end" newline newline ...
        "function R = quat_a_rot(q)" newline ...
        "q0 = q(1); q1 = q(2); q2 = q(3); q3 = q(4);" newline ...
        "R = [1-2*(q2^2+q3^2), 2*(q1*q2-q0*q3), 2*(q1*q3+q0*q2);" newline ...
        "     2*(q1*q2+q0*q3), 1-2*(q1^2+q3^2), 2*(q2*q3-q0*q1);" newline ...
        "     2*(q1*q3-q0*q2), 2*(q2*q3+q0*q1), 1-2*(q1^2+q2^2)];" newline ...
        "end" newline newline ...
        "function r = quat_mult(a,b)" newline ...
        "a0 = a(1); av = a(2:4);" newline ...
        "b0 = b(1); bv = b(2:4);" newline ...
        "r0 = a0*b0 - dot(av,bv);" newline ...
        "rv = a0*bv + b0*av + cross(av,bv);" newline ...
        "r = [r0; rv];" newline ...
        "end" ...
    ];
    % El codigo del bloque MATLAB Function se asigna via Stateflow API.
    sfroot_obj = sfroot;
    chart = sfroot_obj.find( ...
        '-isa', 'Stateflow.EMChart', ...
        'Path', [nombre_modelo '/DinamicaVTOL']);
    if isempty(chart)
        error('No se encontro el bloque MATLAB Function para asignar el script.');
    end
    chart.Script = char(join(codigo_bloque, ""));

    % Conexiones.
    add_line(nombre_modelo, 'IntegradorEstados/1', 'DinamicaVTOL/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'u_control/1', 'DinamicaVTOL/2', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/1', 'IntegradorEstados/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'IntegradorEstados/1', 'estado_x/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/2', 'fuerza_body/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/3', 'momento_body/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'IntegradorEstados/1', 'Scope_estados/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/2', 'Mux_FM/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/3', 'Mux_FM/2', 'autorouting', 'on');
    add_line(nombre_modelo, 'Mux_FM/1', 'Scope_fuerzas_momentos/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'IntegradorEstados/1', 'ToWorkspace_estado_x/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/2', 'ToWorkspace_fuerza_body/1', 'autorouting', 'on');
    add_line(nombre_modelo, 'DinamicaVTOL/3', 'ToWorkspace_momento_body/1', 'autorouting', 'on');

    save_system(nombre_modelo);
    fprintf('Modelo creado: %s.slx\n', nombre_modelo);
end
